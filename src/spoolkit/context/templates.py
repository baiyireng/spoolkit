# 分批推进时，第一批的提示词要补这一句。
#
# 实测教训：只说「最多 2 步」，模型会把**多件事塞进一条步骤**
# （"修复 01 和 02 两道题"）——每一步于是变成一个大活，长任务的
# "小步"前提当场失效（那一步跑了 191 秒）。所以「批的大小」与
# 「步的粒度」必须在提示词里分开说。
