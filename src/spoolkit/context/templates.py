DECOMPOSE = """你负责把一个较大的目标拆成可逐步执行的任务序列。

目标：{goal}

已有信息：
{context}

要求：
- 每一步都必须是「一次能在有限上下文里做完」的单元；
- 每一步应该是可独立验证的功能单元，而不是技术切片。
  错误拆法：把贪吃蛇拆成骨架、初始化变量、移动逻辑、食物逻辑、键盘、渲染；
  这些步骤只是技术切片，各自依赖前一步，单独无法验证，一步做错就会让整条序列失效。
  正确拆法：能动的最小游戏，即骨架、移动、渲染、键盘一次做完 → 加食物和分数
  → 加 game over 和重启；每一步都是完整可运行的功能增量，每一步都能跑通验证，
  步骤之间是功能增量而不是技术依赖；
- 每一步都必须给出可执行的验收标准：能跑什么、看什么、判定依据是什么；
- 每一步都要写 contract：这一步不能动的接口与必须满足的断言。从验收测试里读出
  导入哪个名字、怎么调用、返回什么、边界断言是什么。写清它，执行者就不必自己
  再读一遍测试，实测那一步要多花一轮，而轮数是成本主体；
- 每一步都要声明 scope：这一步允许改动哪些路径，目录前缀或通配符都算。
  范围要尽量窄，它是这一步能自动落盘的边界，写宽了就失去意义；
  但必须覆盖这一步会改到的所有文件，包括为了接线而要动的地方：
  新增一个 CLI 子命令往往要同时改注册它的那个文件，例如 `cli/app.py`；
  新增一个包往往要在 `__init__.py` 里导出。漏掉一处，那处改动会被闸门
  挡在外面，而且你看不到被挡这件事，只会看到验证失败；
- 顺序要正确：后面的步骤可以依赖前面步骤的产物；
- 步骤数量控制在 {limit} 步以内，宁可少而准，不要凑数；
- 不要写「调研一下」「优化一下」这类无法验收的步骤。
- 对单文件任务，每步优先整文件 write_file 而非 patch：分步改同一个文件时，
  每步都要重新读文件再生成 patch，patch 格式容易出错并导致死循环。
  整文件重写可以绕开 patch，代价是容易丢原有内容，所以每步的 scope 要覆盖
  该文件，且步骤粒度要大到「一次写完一个功能」而不是「一次改一行」。
- 每一步都要声明由谁执行，字段名是 executor：
  `self` 表示你自己做。一次改一处、读文件不多的活，自己做更快；
  `subagent` 表示交给子智能体：它在一个独立上下文里实现，再由另一个独立
  上下文审查，最后把结论交回来。适合要读很多文件、但验收标准清楚的活，
  那些细节不必占着你的上下文。派发有固定的几次调用成本，不要把小题派出去。

  判据看这一步要碰多少东西，不要看它像不像一个任务：
  - 只改一处、验收是同一个目录里的一条命令，哪怕得先读那个目录里几个文件，
    用 `self`，自己做一两轮就够；
  - 跨多个目录、要读的文件数不清、或者一处改动会波及别处，才值得派发。
  派发一次要付实现、独立审查、判定好几轮的固定成本，自己做往往一两轮就完了：
  派多了，省下来的上下文还不够付它的成本，而质量并不因此更高。

只输出 JSON。"""

